    easy: { key: "easy", label: "簡單", name: "好畫好猜", pools: ["e"], desc: "都是一看就懂的東西" },
    std:  { key: "std",  label: "標準", name: "日常",     pools: ["m"], desc: "場景、動作、地點與美食" },
    hard: { key: "hard", label: "困難", name: "挑戰",     pools: ["h"], desc: "情境、抽象與俗語" }
