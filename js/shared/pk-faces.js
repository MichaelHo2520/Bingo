/* ============================================================================
   撲克牌牌面(PKFace)—— ★ 排七與大老二**共用同一份**。

   同 js/shared/mj-faces.js(兩款麻將共用 42 種牌面)的理由:牌面複製成兩份的話,
   兩邊不一致時**兩邊各自都不會壞、也不報錯**,沒有任何東西抓得到 ——
   那正是這個專案最痛的一類走鐘(notes/14 的五對 twin 測試全都是為它存在的)。
   所以第七個遊戲(大老二,v1.76.0)進來時把排七的牌面抽成這一支,而不是再畫一份。

   ── ★★ 四個花色一律自繪 SVG,不用 Unicode 字元 ────────────────────────────
     `♣`(U+2663)長什麼樣**完全看字型** —— 各家畫法差很多,縮到 10px 更是糊成一團。
     排七 v1.75.2 使用者的原話:「梅花我覺得不好看,請你去查看標準的牌是什麼樣子,
     我們就畫那一個樣子」。查證後照標準牌面畫:

       黑桃  倒過來的心 + 莖
       紅心  兩瓣一尖
       方塊  菱形
       梅花  **trefoil 三葉草** —— 三個相等的圓繞中心排成正三角形 + 一根短莖
             (源自德式牌的橡實 Eichel,法式改成 trèfle)

     自繪的附帶好處:**字型依賴整個消失**。
     ⚠ 但**純文字訊息**(toast、大廳說明、靜態 HTML 文案)仍然要走各遊戲 rules.js 的
       `suitCh()`(它會補 U+FE0E)—— 那一半沒有 SVG 可用,不加變體選擇子 Android 會把
       ♥ ♦ 渲染成彩色 emoji,字級與對齊當場失控。
     ⚠ 撲克牌 Unicode(**U+1F0A0–U+1F0FF** 那一整段,含牌背、A~K 與小丑)一個都不准用,
       多數字型沒有 → 豆腐方框。同 CLAUDE.md 的麻將牌禁令。
       ⚠ 真正的守門是 e2e 掃**畫面**(單機 e2e 的 L 節掃 `document.body`),不是 repo grep ——
         註解裡本來就會為了說明而提到那些字元(`js/mahjong16/board.js` 就有幾個)。
         但這幾支新檔一律**只寫碼位、不貼字元**,讓 grep 的雜訊少一點。
         (順帶一提 🎴 是 U+1F3B4,不在這一段裡,可以安心用。)

   ── ★ fill:currentColor 是關鍵,不可以改成寫死顏色 ─────────────────────────
     花色的顏色沿用外層 `.sv-card` / `.sv-cell` / `.b2-card` 既有的 `color` 規則,
     所以各遊戲「牌面上用深紅、深色桌面上用亮紅」那兩支變數**一行都不用改**
     (排七 notes/15 第六節那條「紅色有兩支」)。

   ── ★★ 牌面是「點數在上、花色在下,兩件都置中」而且都畫得很大 ────────────────
     排七 v1.75.3 曾經照**標準撲克牌**改成「左上角 index + 牌面一個大 pip」,
     那的確是真牌的畫法(1870 年代發明角落 index 的理由是「扇形持牌時只露左上角
     也要讀得出來」)。使用者看了之後要求**改回置中版,只把字與花色再放大一點**。
     ⚠ 想通這件事的關鍵:**螢幕上的牌不是扇形握在手上的** —— 每一張都完整攤在那裡,
       角落 index 解決的那個問題在這裡根本不存在,它換來的只是「同樣的牌寬要塞兩組
       東西」,於是點數與花色都被迫縮小。置中版可以把整張牌的寬度都給這兩件事。
     > 教訓:**照抄實體物件的規格之前,先問它當初是為了解決什麼問題,那個問題還在不在。**
     字級由各遊戲自己的 CSS 決定(`.sv-cr`/`.sv-cs`、`.b2-cr`/`.b2-cs`)。

   ── 這一支刻意不知道「牌 id 怎麼編碼」──────────────────────────────────────
     排七的花色索引是 0♠ 1♥ 2♦ 3♣、大老二是 0♣ 1♦ 2♥ 3♠(因為那邊的索引要參與比大小)。
     兩邊**不可能共用同一組索引**,所以這支一律吃**花色代號字串**("s"/"h"/"d"/"c"),
     由各遊戲用自己的 `SUIT_KEY[]` 換過來。共用一組索引才是真的會出錯的做法。
   ========================================================================== */

const PKFace = (function(){

  const SUIT_KEYS = ["s", "h", "d", "c"];

  const PATHS = {
    // ♠ 黑桃:倒過來的心 + 莖
    s: '<path d="M50 9C50 9 88 40 88 61c0 12-9 20-20 20-7 0-13-4-18-10-5 6-11 10-18 10-11 0-20-8-20-20C12 40 50 9 50 9z"/>' +
       '<path d="M50 66c0 12-4 21-11 27h22c-7-6-11-15-11-27z"/>',
    // ♥ 紅心:兩瓣一尖
    h: '<path d="M50 90S10 62 10 36C10 22 21 12 34 12c8 0 14 5 16 11 2-6 8-11 16-11 13 0 24 10 24 24 0 26-40 54-40 54z"/>',
    // ♦ 方塊:菱形
    d: '<path d="M50 6 86 50 50 94 14 50z"/>',
    // ♣ 梅花:三葉草(三個 r20 的圓,圓心排成邊長約 31 的正三角形 → 葉瓣充分相接)+ 短莖
    c: '<circle cx="50" cy="31" r="20"/><circle cx="34" cy="58" r="20"/><circle cx="66" cy="58" r="20"/>' +
       '<path d="M50 60c0 14-4 25-11 33h22c-7-8-11-19-11-33z"/>'
  };

  /* 一顆花色。cls = 各遊戲自己的 class(排七 "sv-sv"、大老二 "b2-sv")。 */
  function suitSVG(key, cls){
    return '<svg class="' + cls + '" viewBox="0 0 100 100" aria-hidden="true">' + (PATHS[key] || "") + '</svg>';
  }

  /* 一張牌。o = { prefix, suit, rank, red, cls, data }
       prefix  各遊戲的 class 前綴("sv" / "b2")
       suit    花色代號("s"/"h"/"d"/"c")
       rank    點數的顯示字串("A" / "10" / "K"…)
       red     要不要掛 .red(由各遊戲的 isRed() 決定)
       cls     額外的 class("can" / "no" / "sel" / "tiny"…)
       data    寫進 data-c 的值(各遊戲自己的牌 id)
     ⚠ 產出的 HTML 與排七 v1.75.16 之前**逐字相同** —— 抽出這一支時不可以順手「整理」
       標籤順序或空白,那會讓排七既有的 e2e 與版面截圖全部要重新驗收。 */
  function cardHTML(o){
    const p = o.prefix;
    return '<span class="' + p + '-card' + (o.red ? " red" : "") + (o.cls ? " " + o.cls : "") +
             '" data-c="' + o.data + '">' +
             '<span class="' + p + '-cr">' + o.rank + '</span>' +
             '<span class="' + p + '-cs">' + suitSVG(o.suit, p + "-sv") + '</span>' +
           '</span>';
  }

  /* ★★ 一張**蓋著的牌**(牌背,v1.84.0 為 21 點加)。
       o = { prefix, cls }

     ── 為什麼到第八個遊戲才需要它 ──────────────────────────────────────────
       前七個遊戲的隱藏資訊都是「**防偷看**」:牌在 DB 是明碼,靠顯示端不畫
       (大老二對手的手牌、排七別人蓋掉的牌 —— 那些位置畫的是**張數**,不是牌)。
       21 點的莊家暗牌是**規則本身的一部分** —— 它有一個固定的位置、要看得出
       「那裡有一張牌,只是還沒翻」,所以必須畫得出來。

     ⚠ 圖樣一律交給 CSS(`.<prefix>-bk`)—— 不要在這裡塞 SVG 花紋:
       牌背要跟著主題換色(ebook 模式是純白 + 黑框),寫在 SVG 裡就換不動了。
     ⚠ data-c 刻意給 "?" 而不是真正的牌 id:那個屬性會被點擊處理讀去當牌用
       (`+el.dataset.c`),寫真值等於**把暗牌洩漏在 DOM 屬性裡**。 */
  function backHTML(o){
    const p = (o && o.prefix) || "pk";
    const cls = (o && o.cls) ? " " + o.cls : "";
    return '<span class="' + p + '-card back' + cls + '" data-c="?" aria-label="蓋著的牌">' +
             '<span class="' + p + '-bk" aria-hidden="true"></span>' +
           '</span>';
  }

  return { SUIT_KEYS, PATHS, suitSVG, cardHTML, backHTML };
})();

/* node 測試用(瀏覽器不會有 module) */
if (typeof module !== "undefined" && module.exports) module.exports = PKFace;
