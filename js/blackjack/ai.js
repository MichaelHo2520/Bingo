"use strict";

/* ============================================================================
   21 點 — 電腦對手(BJAI)。
   ★ 純函式,零 DOM / 零 Firebase / 零 MP。只相依 js/blackjack/rules.js(BJ)。
     棋力只有靠 node 大量對局才驗得出來(碰一行 DOM 就只能在瀏覽器裡一局一局手動玩)。

   ── ★★ 目標函數是**籌碼**,不是勝率 ────────────────────────────────────────
     同排七(第一名的比例 vs 平均罰分)與大老二(名次分 vs 平均剩幾張)那一條:
     「贏的局數多」與「賺的籌碼多」在 21 點會給出**相反**的答案 ——
     把每一手都補到 20 會提高單局勝率,但爆掉的那些手輸的是加倍後的注。
     ⚠ 調參一律看「打 N 局之後的淨籌碼」,不要看勝率。

   ── ★★ 這一支不作弊:它只看得到**明牌** ─────────────────────────────────────
     單機時 AI 與我跑在同一台,`st` 裡有莊家的暗牌 —— 讀了就是作弊,
     而作弊的 AI 在體感上只會變成「電腦每次都剛好知道」。
     結構上的保證只有一句話:
         ★ 這一支讀莊家手牌**只准經過 upOf() / visible()**,
           它們一律跳過 `hands[dealer][1]`(未翻開時)。
     ⚠ 不要為了「算得準一點」在別的地方直接索引 st.hands[st.dealer] ——
       那是這一支唯一會靜靜地壞掉的地方(而且測試很難抓:AI 只是變強)。
     ★ 例外**只有一個**:莊家自己就是電腦時(dealerPick),那副牌是他自己的。

   ── ★★ AI 一定要吃房規 ────────────────────────────────────────────────────
     「莊家補牌線」直接決定閒家該補到幾點才划算;「平手莊家吃」會讓閒家必須
     **更積極**補牌(打平沒有用)。所以每一支都吃 st.rules。
     ⚠ 「假綠」的新品種:AI 在預設房規下正常,換一組房規變成亂補,而測試全綠 ——
       調參要在**多組房規**下都驗,不可以只驗預設那一組。
   ========================================================================== */

const BJAI = (function(){

  /* ── ★ 三個難度的階梯是「決策資訊用得多不多」,而不是「敢不敢冒險」──────────
       easy 只看自己的點數,而且亂補
       mid  「照莊家的規矩打」—— 補到 17 就停。★ 完全不看莊家的明牌、也不加倍
       hard 完整基本策略(看明牌)+ 加倍 + 會數這一局翻開的牌
     ⚠⚠ 這個階梯是**量出來的**,不是設計出來的:第一版讓 mid 就走基本策略、
        hard 再「加料」(17 點對大明牌多補一次 + 算牌放寬),結果 hard 反而比 mid 差
        (每單位押注 −9.5% vs −9.2%)—— 因為那兩條加料**本身就是錯的**:
        硬 17 再補的爆牌率約 69%,而基本策略「17 一律停」正是算過的最佳解。
        ★ 教訓:**基本策略已經是最佳解,「高手」不該在它上面加東西,
          而該讓中間那一級少用一點資訊。** 於是 mid 降級成「照莊家的規矩打」
          (那是真人最常見的打法,也確實比較差),階梯就自然成立了。 */
  const LEVEL_INFO = {
    easy: { emoji: "🙂", name: "新手",
            desc: "怕爆 —— 13 點就不敢補了,但有時手癢又多補一張;不看明牌、不會加倍" },
    mid:  { emoji: "🤔", name: "普通",
            desc: "照莊家的規矩打 —— 補到 17 就停;不看莊家的明牌,也不會加倍" },
    hard: { emoji: "😈", name: "高手",
            desc: "完整基本策略(會看莊家的明牌)+ 會加倍 + 會數這一局翻開的牌" }
  };
  const LEVEL_KEYS = ["easy", "mid", "hard"];
  const levelOf = k => LEVEL_INFO[k] || LEVEL_INFO.mid;
  /* 可見的思考時間。⚠ 一定要有:算完只花 1ms 的話幾家會在同一格瞬間打完,
     玩家看到的是「畫面忽然全變了」,根本讀不出剛才發生什麼事(同大老二 / 排七)。 */
  const THINK = { easy: 520, mid: 640, hard: 760 };
  const thinkMs = k => THINK[k] || THINK.mid;

  /* ==========================================================================
     一、★ AI 眼中的世界(只有明牌)
     ========================================================================== */
  /* 莊家的**明牌**(第一張)。⚠ 只有這一支可以碰 st.hands[st.dealer]。 */
  function upOf(st){
    const h = st.hands[st.dealer];
    return (h && h.length) ? h[0] : -1;
  }
  /* 明牌的「策略點數」:A 一律當 11(基本策略表的慣例),J/Q/K 當 10。 */
  function upValue(st){
    const c = upOf(st);
    if(c < 0) return 10;
    const r = BJ.rankOf(c);
    return r === 1 ? 11 : Math.min(r, 10);
  }
  /* 場上翻開的所有牌 = 每個閒家的整手 + 莊家的明牌(未翻開時)。
     ★ 「高手」數的就是這一份 —— 一副牌每局重洗,所以能數的只有**這一局**,
       而這一局的資訊確實足以微調(例如 10 點的牌已經出掉一半 → 補牌比較不容易爆)。
     ⚠ st.reveal 是唯一的判斷式(見 rules.js 第六節):翻開了就整副都看得到。 */
  function visible(st){
    const out = [];
    for(let s = 0; s < st.n; s++){
      if(s === st.dealer && !st.reveal){ const c = upOf(st); if(c >= 0) out.push(c); continue; }
      const h = st.hands[s] || [];
      for(let i = 0; i < h.length; i++) out.push(h[i]);
    }
    return out;
  }
  /* 「再補一張會爆」的機率(只用明牌修正牌堆)。
     ⚠ 這是**估計**不是真值:剩下的牌裡有多少張讓我爆,分母用「52 − 看得到的」。
       一副牌每局重洗,所以不必也不能跨局累積。 */
  function bustOdds(st, hand){
    const v = BJ.valueOf(hand);
    if(v.bust) return 1;
    const room = 21 - v.best;             // 補進來的點數超過這個就爆
    const seen = {};
    visible(st).forEach(c => { seen[c] = 1; });
    let bad = 0, tot = 0;
    for(let c = 0; c < BJ.NCARD; c++){
      if(seen[c]) continue;
      tot++;
      const r = BJ.rankOf(c);
      const add = r === 1 ? 1 : Math.min(r, 10);    // A 一律當 1(它永遠不會讓人爆)
      if(add > room) bad++;
    }
    return tot ? bad / tot : 0;
  }

  /* ==========================================================================
     二、基本策略表(無分牌 / 無保險 / 無投降,莊家軟 17 停)
     ──────────────────────────────────────────────────────────────────────────
       回傳 "h" | "s" | "d"(呼叫端會再過一次 BJ.legal,加倍不合法時自動退成 "h")。
       up = 莊家明牌的策略點數(2..11)。

       ★ 這張表是「**期望籌碼**最大」的解,不是「勝率最大」——
         12~16 對 2~6 停牌的理由正是莊家爆牌率高,而不是我這手很強。
       ⚠ 表是照「平手退注」算出來的。房規改成**平手莊家吃**時打平沒有用 →
         下面 adjust() 會把邊界往「多補一點」推(見那一段)。
     ========================================================================== */
  function hardMove(total, up){
    if(total >= 17) return "s";
    if(total >= 13) return up <= 6 ? "s" : "h";        // 13~16
    if(total === 12) return (up >= 4 && up <= 6) ? "s" : "h";
    if(total === 11) return up <= 10 ? "d" : "h";
    if(total === 10) return up <= 9 ? "d" : "h";
    if(total === 9)  return (up >= 3 && up <= 6) ? "d" : "h";
    return "h";                                        // 8 以下一律補
  }
  function softMove(total, up){
    if(total >= 19) return "s";                        // A,8 / A,9
    if(total === 18){                                   // A,7
      if(up === 2 || up === 7 || up === 8) return "s";
      if(up >= 3 && up <= 6) return "d";
      return "h";                                       // 9 / 10 / A
    }
    if(total === 17) return (up >= 3 && up <= 6) ? "d" : "h";     // A,6
    if(total >= 15) return (up >= 4 && up <= 6) ? "d" : "h";      // A,4 / A,5
    return (up >= 5 && up <= 6) ? "d" : "h";                       // A,2 / A,3
  }
  function basic(hand, up){
    const v = BJ.valueOf(hand);
    if(v.bust) return "s";
    // 軟手 = 有 A 而且升成 11 沒爆(而且只有兩張時才考慮加倍,那由 legal 過濾)
    if(v.soft) return softMove(v.soft, up);
    return hardMove(v.hard, up);
  }

  /* ★★ 數牌微調 —— 只給「高手」,而且**只往安全的方向推一格**。
     ⚠⚠ 這裡曾經有兩條反方向的加料,兩條都**量出來是扣分的**,已經拿掉:
        ① 「硬 17 對大明牌多補一次」→ 爆牌率約 69%,而基本策略「17 一律停」
           就是算過的最佳解。加了它 hard 的期望從 −9.2% 掉到 −9.5%。
        ② 「表說停、但爆牌機率低就補」→ 同一個方向的錯:12~16 對小明牌停牌
           的理由是**莊家爆牌率高**,不是我這手安全,所以「我補了不會爆」不構成理由。
     ★ 留下來的只有一條,而它是**反向**的:表說補、但這一局翻開的牌讓補牌幾乎必爆
       → 那就停。典型情境是 16 對莊家 10(基本策略叫你補,那本來就是勝率最低的一格),
       而場上小牌已經出掉大半的時候,停牌變成比較好的選擇。
     ⚠ 門檻 0.70 是量出來的:再低會開始亂停(退化成 mid),再高就等於沒作用。
     ⚠ **它的貢獻很小**,照實記下來免得日後有人以為這裡藏著什麼:
       12 萬局的對照組是 **+0.22pp**(預設房規)/ **+0.03pp**(補 17 + 平手退注)。
       方向正確、留著,但**不要**在它身上再疊東西 —— 上面那兩條就是這樣加壞的。 */
  function adjust(mv, hand, st){
    if(mv !== "h") return mv;
    const v = BJ.valueOf(hand);
    if(v.soft) return mv;                              // 軟手補牌不會爆,這條不適用
    if(v.hard < 14 || v.hard > 16) return mv;          // 只管 14~16 那三格
    return bustOdds(st, hand) > 0.70 ? "s" : mv;
  }

  /* ==========================================================================
     三、閒家這一手
     ========================================================================== */
  function pick(st, seat, level){
    const lg = BJ.legal(st, seat);
    if(!lg.hit && !lg.stand) return null;
    const hand = st.hands[seat];
    const L = level || "mid";
    let mv;

    if(L === "easy"){
      /* ★ 新手 = **怕爆**:13 點就不敢補了(那是真人最常見的錯 —— 12~16 對小明牌
         停牌的理由是莊家爆牌率高,而他停的理由只是「我怕爆」,方向剛好相反),
         但有時候手癢又多補一張。不看明牌、也**不會加倍**。
         ⚠ 這幾個數字是量出來的:8 萬局的對照組裡
             「補到 15 才停」= −15.9% · 「停在 15」= −15.7% · **這一版** = −17.2%
             · 「停在 13 完全不亂補」= −18.0% · 普通(補到 17)= −15.0%
           前兩種與普通只差 0.9pp,在幾千局的樣本裡被雜訊蓋掉 →
           **難度階梯量不出來就等於沒有**。這一版差 2.2pp,而且亂補讓它不像機器人。
         ⚠ 「亂」也要有上限:17 以上一律停 —— 再亂補會爆到看起來像壞掉,那不是新手是亂數。 */
      const v = BJ.valueOf(hand);
      mv = v.best < 13 ? "h" : (v.best < 17 && Math.random() < 0.45 ? "h" : "s");
    }else if(L === "hard"){
      // ★ 完整基本策略(看莊家明牌)+ 會加倍 + 一條反向的數牌微調(見 adjust)
      mv = adjust(basic(hand, upValue(st)), hand, st);
    }else{
      /* 普通:**照莊家的規矩打** —— 補到 17 就停,完全不看莊家的明牌、也不加倍。
         ★ 這是真人最常見的打法,而它確實比基本策略差一截(量出來每單位押注差 1~7%)
           —— 難度階梯就是靠這一級「少用資訊」成立的(見 LEVEL_INFO 的那段)。 */
      mv = BJ.valueOf(hand).best < 17 ? "h" : "s";
    }

    // ★ 加倍不合法時退成補牌(表裡的 "d" 本來就是「能加倍就加倍,否則補」)
    if(mv === "d" && !lg.dbl) mv = "h";
    if(mv === "h" && !lg.hit) mv = "s";
    if(mv === "s" && !lg.stand) mv = lg.hit ? "h" : null;
    return mv;
  }

  /* ==========================================================================
     四、莊家這一手(只有房規是「自由」時才會被呼叫)
     ──────────────────────────────────────────────────────────────────────────
       ★ 這裡是唯一可以看整副莊家手牌的地方 —— **那是他自己的牌**。
       ★ 真人莊的樂趣在於「他要自己判斷」,所以電腦當莊也不該只會補到 17:
         全場都爆了就直接停(已經通吃,再補是白冒風險),
         贏得過最好的那家就停,贏不過就補。
       ⚠ 房規有補牌線時**不走這裡**(BJ.autoDealer 算得出整段,連等他點都不必)。
     ========================================================================== */
  function dealerPick(st, level){
    const d = st.dealer;
    const lg = BJ.legal(st, d);
    if(!lg.hit && !lg.stand) return null;
    const v = BJ.valueOf(st.hands[d]);
    if(v.bust) return "s";
    if(level === "easy") return v.best < 16 ? "h" : "s";

    // 沒爆的閒家裡最好的那個點數
    let best = -1, alive = 0;
    for(let s = 0; s < st.n; s++){
      if(s === d) continue;
      const pv = BJ.valueOf(st.hands[s]);
      if(!pv.bust){ alive++; if(pv.best > best) best = pv.best; }
    }
    // ★ 全部爆了 → 已經通吃,一張都不必補(補了反而可能自己爆 → 那是純虧)
    if(!alive) return "s";
    if(level === "mid") return v.best < 17 ? "h" : "s";

    // 高手:打得贏就停。★ 平手莊家吃時「打平」就夠了
    const need = st.rules.pushDealer ? best : best + 1;
    if(v.best >= need) return "s";
    if(v.best >= 18) return "s";              // 18 以上再補幾乎必爆,認賠比較划算
    if(bustOdds(st, st.hands[d]) > 0.72) return "s";
    return "h";
  }

  /* ==========================================================================
     五、押注
     ──────────────────────────────────────────────────────────────────────────
       ★ 目標函數是籌碼 → 押注大小與補牌決策**要一起評估**:
         全押然後亂補 vs 小押然後照基本策略,勝率可能一樣但籌碼曲線天差地遠。
       ★ 「落後時押大」在名次制下是理性的(反正比的是誰的淨變化大)。
       net = 這一場到目前為止的淨籌碼變化(可以是負的)。
     ========================================================================== */
  function bet(rules, net, level){
    const tiers = BJ.betTiers(rules.betMax);
    if(level === "easy") return tiers[Math.floor(Math.random() * tiers.length)];
    // 普通:保守,永遠押最小的檔
    if(level === "mid") return tiers[0];
    /* ★★ 高手:**沒落後就押最小**。
       ⚠⚠ 這一條是量出來的,而它一開始是反的:第一版讓高手在平盤時押中間偏大的檔,
          結果它的淨籌碼比普通還慘(−3090 vs −1318)。原因很單純 ——
          **當閒家的期望值是負的**(平手莊家吃 + 閒家先爆先輸就是莊家的優勢),
          所以「押得多」直接等於「輸得多」,而決策品質再好也翻不過那個負號。
          ★ 教訓:目標函數是籌碼時,**押注大小的影響遠大於補牌決策**,
            所以調 AI 一定要把兩件事分開量(先固定押注量決策、再量押注)。
       ★ 落後才押大:比的是名次(誰的淨籌碼多),落後時變異數是朋友。 */
    if(net < 0) return tiers[tiers.length - 1];
    return tiers[0];
  }

  return {
    LEVEL_INFO, LEVEL_KEYS, levelOf, thinkMs,
    // AI 的世界觀(★ 只有明牌)
    upOf, upValue, visible, bustOdds,
    // 決策
    hardMove, softMove, basic, adjust, pick, dealerPick, bet
  };
})();

/* node 測試用(瀏覽器不會有 module) */
if (typeof module !== "undefined" && module.exports) module.exports = BJAI;
