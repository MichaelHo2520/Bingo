  /* ---------- 保唯一性變換 ---------- */
  function shuffled(k){
    const a=[]; for(let i=0;i<k;i++)a.push(i);
    for(let i=k-1;i>0;i--){ const j=Math.floor(Math.random()*(i+1)); const t=a[i]; a[i]=a[j]; a[j]=t; }
    return a;
  }
  // 列的新順序:band 之間先洗一次,每個 band 內部再洗一次
  function axisOrder(total, groupSize){
    const groups=total/groupSize, gOrder=shuffled(groups), out=[];
    for(let g=0; g<groups; g++){
      const inner=shuffled(groupSize);
      for(let k=0;k<groupSize;k++) out.push(gOrder[g]*groupSize + inner[k]);
    }
    return out;   // out[新位置] = 舊位置
  }
  function transform(puzArr, solArr, n, bw, bh){
    const rowOrder=axisOrder(n, bh);      // 同一 band = 連續 bh 列
    const colOrder=axisOrder(n, bw);      // 同一 stack = 連續 bw 行
    const dig=[0].concat(shuffled(n).map(v=>v+1));   // 0(空格)保持 0
    const doTranspose = (bw===bh) && Math.random()<0.5;   // 宮非正方形(6×6)不可轉置
    const map=(src)=>{
      const out=new Array(n*n);
      for(let r=0;r<n;r++) for(let c=0;c<n;c++){
        const v=src[rowOrder[r]*n + colOrder[c]];
        const tv=dig[v];
        if(doTranspose) out[c*n+r]=tv; else out[r*n+c]=tv;
      }
      return out;
    };
    return { puz:map(puzArr), sol:map(solArr) };
  }

  /* ---------- 對外 ---------- */
  function parse(str){ return String(str).split("").map(ch=>ch==="."?0:(+ch||0)); }
  function stringify(arr){ return arr.map(v=>v?String(v):".").join(""); }

  // 產生一題:回傳 { level, n, bw, bh, puzzle, sol, holes }
  function make(levelKey){
    const L=LEVELS[levelKey]||LEVELS.e9;
    const bank=SEEDS[L.key];
    const seed=bank[Math.floor(Math.random()*bank.length)];
    const t=transform(parse(seed[0]), parse(seed[1]), L.n, L.bw, L.bh);
    return {
      level:L.key, n:L.n, bw:L.bw, bh:L.bh,
      puzzle:stringify(t.puz), sol:stringify(t.sol),
      holes:t.puz.filter(v=>!v).length
    };
  }
